use rand::{Rng, rngs::StdRng};

fn gcd(mut a: u32, mut b: u32) -> u32 {
    while b != 0 {
        (a, b) = (b, a % b);
    }
    a
}

fn radical(mut n: u32) -> u32 {
    let mut result = 1;
    let factor_bound = n;
    for p in 2..=factor_bound {
        if n.is_multiple_of(p) {
            result *= p;
            while n.is_multiple_of(p) {
                n /= p;
            }
        }
        if n == 1 {
            break;
        }
    }
    result
}

fn divisors(n: u32) -> Vec<u32> {
    (2..n).filter(|d| n.is_multiple_of(*d)).collect()
}

fn pick(rng: &mut StdRng, values: &[u32]) -> u32 {
    values[rng.random_range(0..values.len())]
}

fn inverse(n: u32, a: u32) -> Option<u32> {
    (1..n).find(|b| a * b % n == 1)
}

fn nilpotence_index(n: u32, x: u32) -> Option<u32> {
    let mut power = 1;
    for k in 1..=n {
        power = power * x % n;
        if power == 0 {
            return Some(k);
        }
    }
    None
}

pub fn generate(rng: &mut StdRng) -> String {
    let composites: Vec<_> = (4..=120).filter(|&n| !divisors(n).is_empty()).collect();
    let n = pick(rng, &composites);
    describe(rng, n)
}

fn describe(rng: &mut StdRng, n: u32) -> String {
    let units: Vec<_> = (1..n).filter(|&x| gcd(n, x) == 1).collect();
    let unit = pick(rng, &units[1..]);
    let inv = inverse(n, unit).unwrap();
    let zero_divisors: Vec<_> = (1..n).filter(|&x| gcd(n, x) != 1).collect();
    let z = pick(rng, &zero_divisors);
    let witness = n / gcd(n, z);
    let d = pick(rng, &divisors(n));
    let a = rng.random_range(1..n);
    let b = rng.random_range(1..n);
    let rad = radical(n);
    let nilpotents = if rad == n {
        format!("{n} is squarefree: 0 is the only nilpotent, so R is reduced.")
    } else {
        let x = rad * rng.random_range(1..n / rad);
        let k = nilpotence_index(n, x).unwrap();
        format!(
            "Nonzero nilpotent [{x}] has least nilpotence index {k}: [{x}]^{k} = [0]. R is not reduced."
        )
    };
    format!(
        "R = Z/{n}Z, a commutative ring with identity [1] and characteristic {n}. \
         [x] = [y] iff {n} divides x-y; addition and multiplication reduce ordinary integer operations modulo {n}.\n\
         [{a}][{b}] = [{}]. The units are exactly [x] with gcd(x,{n}) = 1 ({} units); [{unit}]^(-1) = [{inv}].\n\
         The {} nonzero zero divisors are exactly [x] with 1 <= x < {n} and gcd(x,{n}) > 1; [{z}][{witness}] = [0], with both factors nonzero.\n\
         Nilpotents are exactly the multiples of rad({n}) = {rad}, including 0 ({} elements). {nilpotents}\n\
         The proper nonzero ideal I = <[{d}]> consists of residues divisible by {d} and has {} elements. \
         Ann(I) = <[{}]> has {d} elements. Every ideal of R is generated by a divisor of {n}.\n\
         R/I is isomorphic to Z/{d}Z via [x] + I -> x mod {d}; the surjective map R -> Z/{d}Z has kernel I.",
        a * b % n,
        units.len(),
        zero_divisors.len(),
        n / rad,
        n / d,
        n / d,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use rand::SeedableRng;
    use std::collections::HashSet;

    #[test]
    fn exhaustive_ring_invariants() {
        for n in 4..=120 {
            for x in 0..n {
                assert_eq!(inverse(n, x).is_some(), gcd(n, x) == 1);
                let annihilates_nonzero = (1..n).any(|y| x * y % n == 0);
                if x != 0 {
                    assert_eq!(annihilates_nonzero, gcd(n, x) > 1);
                    if gcd(n, x) > 1 {
                        let witness = n / gcd(n, x);
                        assert!((1..n).contains(&witness));
                        assert_eq!(x * witness % n, 0);
                    }
                }
                // Repeated multiplication gives a factorization-independent oracle.
                assert_eq!(nilpotence_index(n, x).is_some(), x % radical(n) == 0);
            }
            for d in divisors(n) {
                let ideal: HashSet<_> = (0..n).map(|x| d * x % n).collect();
                assert_eq!(ideal.len(), (n / d) as usize);
                let annihilator: HashSet<_> = (0..n)
                    .filter(|&x| ideal.iter().all(|&i| x * i % n == 0))
                    .collect();
                assert_eq!(annihilator.len(), d as usize);
                assert_eq!(annihilator, (0..n).map(|x| (n / d) * x % n).collect());
                for x in 0..n {
                    assert_eq!(ideal.contains(&x), x % d == 0);
                    for y in 0..n {
                        assert_eq!((x * y % n) % d, (x % d) * (y % d) % d);
                        assert_eq!(((x + y) % n) % d, ((x % d) + (y % d)) % d);
                        assert_eq!(ideal.contains(&((x + n - y) % n)), x % d == y % d);
                    }
                }
            }
        }
    }

    #[test]
    fn seeded_variety_and_samples() {
        let mut seen = HashSet::new();
        let mut moduli = HashSet::new();
        for seed in 0..512 {
            let text = generate(&mut StdRng::seed_from_u64(seed));
            assert!(!text.ends_with('\n'));
            moduli.insert(text.split(',').next().unwrap().to_string());
            seen.insert(text.clone());
            if seed < 2 {
                println!("{text}\n");
            }
            assert_eq!(text, generate(&mut StdRng::seed_from_u64(seed)));
        }
        assert!(seen.len() >= 500);
        assert!(moduli.len() > 70);
    }
}
