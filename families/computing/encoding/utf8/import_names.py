"""Rebuild the pinned Unicode 15.0.0 name subset, using Python 3.12's UCD."""

import argparse
import hashlib
import json
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parent
VERSION = "15.0.0"
# Unicode 15.0.0 Blocks.txt boundaries; unassigned points are omitted.
BLOCKS = [
    (0x0000, 0x007F, "Basic Latin"),
    (0x0080, 0x00FF, "Latin-1 Supplement"),
    (0x0300, 0x036F, "Combining Diacritical Marks"),
    (0x0370, 0x03FF, "Greek and Coptic"),
    (0x2000, 0x206F, "General Punctuation"),
    (0x2190, 0x21FF, "Arrows"),
    (0x2200, 0x22FF, "Mathematical Operators"),
    (0x2300, 0x23FF, "Miscellaneous Technical"),
    (0x1D100, 0x1D1FF, "Musical Symbols"),
    (0x1F600, 0x1F64F, "Emoticons"),
]


def render():
    if unicodedata.unidata_version != VERSION:
        raise RuntimeError(f"Need UCD {VERSION}, found {unicodedata.unidata_version}")
    rows = []
    for first, last, block in BLOCKS:
        for cp in range(first, last + 1):
            name = unicodedata.name(chr(cp), None)
            if name is not None:
                rows.append((cp, name, block))
    lines = [
        "// Generated by import_names.py from Unicode 15.0.0; see LICENSE.txt.",
        "pub(super) const NAMES: &[(u32, &str, &str)] = &[",
    ]
    lines.extend(f"    (0x{cp:04X}, {json.dumps(name)}, {json.dumps(block)})," for cp, name, block in rows)
    lines.append("];")
    # Match rustfmt for long entries, without depending on a Rust toolchain here.
    import subprocess
    result = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input="\n".join(lines) + "\n", text=True, capture_output=True, check=True)
    return result.stdout.replace("\r\n", "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    path = ROOT / "names.rs"
    if args.check:
        if path.read_text(encoding="utf-8") != text:
            raise SystemExit("names.rs differs; run import_names.py")
    else:
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"Unicode {VERSION}, sha256 {hashlib.sha256(text.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
