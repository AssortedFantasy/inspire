"""Verify the pinned fabric vocabulary and regenerate the sixteen leaf adapters.

Outfit construction lives in outfit.rs; the source supplies vocabulary only.
Run from any directory with python -B families/design/wardrobe/import_fabrics.py.
"""

from pathlib import Path
import hashlib
import json
import urllib.request

ROOT = Path(__file__).resolve().parents[3]
REVISION = "2e7adec11a0561696c236ae1fca82e88be173d42"
URL = f"https://raw.githubusercontent.com/dariusk/corpora/{REVISION}/data/materials/fabrics.json"
SHA256 = "6f4314342350c91f1457f3c20c0f37cf0c2149c12306c556302798a3ccae9684"
ACCEPTED = {
    "cotton", "linen", "wool", "nylon", "polyester", "poplin", "oxford",
    "denim", "canvas", "corduroy", "seersucker", "chambray", "twill",
    "jersey", "flannel", "gabardine", "polar fleece", "ripstop", "tweed",
}
CONTEXTS = ("everyday", "office", "dinner", "trail")
WEATHER = ("warm", "mild", "rain", "cold")


def source(context, weather):
    return f'''// Generated by ../../import_fabrics.py; outfit construction is in ../../outfit.rs.
mod outfit {{
    include!("../../outfit.rs");
}}

use rand::rngs::StdRng;

pub fn generate(rng: &mut StdRng) -> String {{
    outfit::generate(rng, {context}, {weather})
}}

#[cfg(test)]
mod tests {{
    #[test]
    fn outfit_structure_and_weather() {{
        super::outfit::check({context}, {weather});
    }}
}}
'''


def main():
    cache = ROOT / "target/imports/corpora/data/materials/fabrics.json"
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(URL) as response:
            cache.write_bytes(response.read())
    raw = cache.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError("Pinned fabrics checksum mismatch")
    vocabulary = set(json.loads(raw)["fabrics"])
    if not ACCEPTED <= vocabulary:
        raise ValueError(f"Absent reviewed fabric names: {ACCEPTED - vocabulary}")
    base = Path(__file__).resolve().parent
    for context, context_name in enumerate(CONTEXTS):
        for weather, weather_name in enumerate(WEATHER):
            leaf = base / context_name / weather_name
            leaf.mkdir(parents=True, exist_ok=True)
            (leaf / "generator.rs").write_text(source(context, weather), encoding="utf-8")
    print("Generated 16 wardrobe adapters; verified 19 Corpora fabric names.")


if __name__ == "__main__":
    main()
